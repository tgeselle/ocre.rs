//! Framework translations compiled into the binary as tables (nothing to
//! parse): validation messages (`errors.*`), month and day names and formats
//! (`date.*`, `time.*`), number formats (`number.*`) and `time_ago_in_words`
//! (`datetime.distance_in_words.*`), for English, French, German, Spanish,
//! Italian, Portuguese and Dutch. Keys and wording follow rails-i18n; the
//! app's locale files win over them. Plural keys end in `.one`/`.other`;
//! name lists are comma-separated, as the YAML subset has no lists.

use super::plural::Rule;

type Entries = &'static [(&'static str, &'static str)];

const LANGUAGES: [(&str, Entries); 7] =
    [("en", EN), ("fr", FR), ("de", DE), ("es", ES), ("it", IT), ("pt", PT), ("nl", NL)];

fn entries(code: &str) -> Option<Entries> {
    let language = super::primary(code);
    LANGUAGES.iter().find(|(name, _)| name.eq_ignore_ascii_case(language)).map(|(_, entries)| *entries)
}

/// The `errors.messages` key whose English text is `message` exactly (`has
/// already been taken` is `taken`), for errors added with a plain message.
pub(super) fn english_key(message: &str) -> Option<&'static str> {
    EN.iter().find_map(|(key, text)| key.strip_prefix("errors.messages.").filter(|_| *text == message))
}

/// The built-in text of `key` for the language of `code`: plain text, or
/// with a count the plural form of the language's rule, else `other`.
pub(super) fn get(code: &str, key: &str, count: Option<i64>) -> Option<&'static str> {
    let entries = entries(code)?;
    let find = |form: Option<&str>| {
        entries
            .iter()
            .find(|(name, _)| match form {
                None => *name == key,
                Some(form) => name.strip_prefix(key).and_then(|rest| rest.strip_prefix('.')) == Some(form),
            })
            .map(|(_, text)| *text)
    };
    find(None).or_else(|| match count {
        Some(n) => find(Some(Rule::for_locale(code).category(n).name())).or_else(|| find(Some("other"))),
        None => find(Some("other")),
    })
}

