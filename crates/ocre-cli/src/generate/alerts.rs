//! `ocre generate alerts`: the `alerts` table of `ocre::alerts` (owner
//! alerts by email, deduplicated and capped), and `ALERT_EMAIL` in
//! `.dev.vars`.

use super::Edits;
use crate::{CliResult, output::CliError, project::Project};

pub fn alerts(project: &Project) -> CliResult {
    let mut edits = Edits::new(project);
    if edits.has_create_migration("alerts")? {
        return Err(CliError::new("this app already has the alerts table")
            .hint("nothing to generate: call ocre::alerts::record(&ctx, Alert::new(\"reason\")).await"));
    }
    let path = super::next_migration_path(&edits, "create_alerts")?;
    let sql = format!(
        "-- Generated by `ocre g alerts`: one row per owner alert (ocre::alerts), kept {} days.\n{}",
        ocre::alerts::KEEP_DAYS,
        ocre::alerts::TABLE_SQL
    );
    edits.create(&path, sql)?;
    if let Some(vars) = edits.read(".dev.vars")?
        && !vars.lines().any(|line| line.split('=').next().is_some_and(|key| key.trim() == ocre::alerts::ALERT_EMAIL))
    {
        let vars = if vars.is_empty() || vars.ends_with('\n') { vars } else { format!("{vars}\n") };
        edits.update(".dev.vars", format!("{vars}{}=owner@example.com\n", ocre::alerts::ALERT_EMAIL));
    }
    let mut report = edits.apply("generate alerts")?;
    report.next = vec![
        "ocre migrate".to_owned(),
        "record alerts: ocre::alerts::record(&ctx, ocre::alerts::Alert::new(\"payment.failed\").key(user_id)).await"
            .to_owned(),
        "send the digest of held-back alerts: ocre g schedule alert_digest \"every 15 minutes\", calling ocre::alerts::send_digest(ctx)"
            .to_owned(),
        "production: ALERT_EMAIL (your address) in worker.env of cloudflare.config.ts".to_owned(),
    ];
    Ok(report)
}
