//! `ocre generate push`: web push notifications on top of `ocre g pwa`'s
//! service worker. `src/push.rs` stores the browsers' subscriptions in
//! `push_subscriptions` and sends to them (`notify_all`, or `notify_user`
//! after `ocre g auth`); `push.js` subscribes the browser from a button
//! with `data-push-subscribe`; a VAPID key pair goes to `.dev.vars`.

use super::{Edits, next_migration_path, register_routes, with_ocre_feature};
use crate::{CliResult, config, output::CliError, project::Project};

const LAYOUT: &str = "templates/layout.html";

const SCRIPT: &str = r#"// Web push subscriptions, generated by `ocre g push`. A click on an element
// with `data-push-subscribe` asks for permission (browsers only allow it
// after a click) and subscribes this browser: `push:subscribed` then fires
// on the element, or `push:error` (call preventDefault() to skip the alert).
// Safari on iPhone and iPad allows it once the site is on the Home Screen.
(() => {
  const bytes = (base64) =>
    Uint8Array.from(atob(base64.replace(/-/g, "+").replace(/_/g, "/") + "=".repeat((4 - (base64.length % 4)) % 4)), (c) =>
      c.charCodeAt(0),
    );

  const subscribe = async () => {
    if (!("serviceWorker" in navigator) || !("PushManager" in window)) throw new Error("This browser cannot receive notifications.");
    if ((await Notification.requestPermission()) !== "granted") throw new Error("Notifications are blocked for this site.");
    const registration = await navigator.serviceWorker.ready;
    const key = await (await fetch("/push/key")).text();
    const subscription =
      (await registration.pushManager.getSubscription()) ||
      (await registration.pushManager.subscribe({ userVisibleOnly: true, applicationServerKey: bytes(key) }));
    const response = await fetch("/push/subscriptions", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify(subscription),
    });
    if (!response.ok) throw new Error(`The app answered ${response.status}.`);
    return subscription;
  };

  window.ocrePush = { subscribe };
  document.addEventListener("click", async (event) => {
    const button = event.target.closest("[data-push-subscribe]");
    if (!button) return;
    event.preventDefault();
    try {
      await subscribe();
      button.dispatchEvent(new CustomEvent("push:subscribed", { bubbles: true }));
    } catch (error) {
      const unhandled = button.dispatchEvent(new CustomEvent("push:error", { bubbles: true, cancelable: true, detail: { error } }));
      if (unhandled) alert(error.message);
    }
  });
})();
"#;

